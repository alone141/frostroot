// Where a disk image keeps what frostroot adds to it. The set-password
// program and its unit are frostroot's own, under /usr/lib as a
// distribution's are; the rest are the files the first boot reads.
const (
	diskFstabPath          = "/etc/fstab"
	diskRepartPath         = "/usr/lib/repart.d/50-root.conf"
	diskGrubConfigPath     = "/boot/grub/grub.cfg"
	diskNetplanPath        = "/etc/netplan/50-frostroot.yaml"
	diskHostnamePath       = "/etc/hostname"
	diskLocaleConfPath     = "/etc/locale.conf"
	diskVconsolePath       = "/etc/vconsole.conf"
	diskSetPasswordPath    = "/usr/lib/frostroot/set-password"
	diskSetPasswordUnit    = "frostroot-set-password.service"
	diskSSHKeygenUnit      = "frostroot-ssh-keygen.service"
	diskUnitDir            = "/usr/lib/systemd/system"
	diskScriptName         = "frostroot-disk" // $0 of the disk script, shown in its error messages
	diskKernelCommandLine  = "ro console=ttyS0 console=tty0"
	diskRootMountOptions   = "defaults,x-systemd.growfs"
	diskESPMountOptions    = "umask=0077,nofail"
	diskMachineIDUninitial = "uninitialized"
)

// diskPerMachineFiles are what no shared image may carry, which the disk
// script removes last: the SSH host keys openssh-server's postinst made,
// the seeds and secrets systemd keeps per machine, and what mmdebstrap's
// cleanup/reproducible would remove, which a disk build skips because that
// cleanup would empty machine-id again after the script wrote it.
var diskPerMachineFiles = []string{
	"/etc/ssh/ssh_host_*_key", "/etc/ssh/ssh_host_*_key.pub",
	"/var/lib/dbus/machine-id", "/var/lib/systemd/random-seed", "/var/lib/systemd/credential.secret", "/etc/machine-info",
	"/var/log/dpkg.log", "/var/log/apt/history.log", "/var/log/apt/term.log", "/var/log/alternatives.log",
	"/var/cache/ldconfig/aux-cache", "/var/log/apt/eipp.log.xz",
}

// diskPackagesToInstall returns what a disk image of release installs:
// the WSL image's packages, then the release's disk packages, once each.
func diskPackagesToInstall(imageRecipe recipe.Recipe, release distro.Release) []string {
	packages := PackagesToInstall(imageRecipe)
	for _, name := range release.DiskPackages {
		if !contains(packages, name) {
			packages = append(packages, name)
		}
	}
	return packages
}

func contains(names []string, name string) bool {
	for _, candidate := range names {
		if candidate == name {
			return true
		}
	}
	return false
}

// DiskStageOptions say what WriteStage renders for a disk image, beyond the
// provisioning every image gets.
type DiskStageOptions struct {
	identifiers diskIdentifiers
	release     distro.Release
}

// stagedDiskFile is one file the disk hooks upload into the image.
type stagedDiskFile struct {
	hostPath  string // in the stage
	imagePath string
}

// diskFile is one rendered file of a disk image: its path in the image and
// its name in the stage.
type diskFile struct {
	imagePath string
	stageName string
	content   string
}

// renderDiskFiles renders every file a disk image holds beyond a WSL
// image's, and the script that places what a file cannot say: the user's
// locked password, the links, the removals.
func renderDiskFiles(imageRecipe recipe.Recipe, options DiskStageOptions) ([]diskFile, string, error) {
	ids := options.identifiers
	files := []diskFile{
		{diskFstabPath, "fstab", renderFstab(ids)},
		{diskRepartPath, "50-root.conf", diskRepartConf},
		{diskGrubConfigPath, "grub.cfg", renderGrubConfig(ids)},
		{diskNetplanPath, "50-frostroot.yaml", diskNetplan},
		{diskHostnamePath, "hostname", imageRecipe.Image.Name + "\n"},
		{diskLocaleConfPath, "locale.conf", "LANG=" + localeOrDefault(imageRecipe) + "\n"},
		{diskVconsolePath, "vconsole.conf", diskVconsole},
		{diskSetPasswordPath, "set-password", renderSetPassword()},
		{diskUnitDir + "/" + diskSetPasswordUnit, diskSetPasswordUnit, renderSetPasswordUnit(imageRecipe.User.Name)},
	}
	if options.release.FirstBootSSHKeys {
		files = append(files, diskFile{diskUnitDir + "/" + diskSSHKeygenUnit, diskSSHKeygenUnit, diskSSHKeygenService})
	}
	script, err := renderDiskScript(imageRecipe, options.release)
	if err != nil {
		return nil, "", err
	}
	return files, script, nil
}

// localeOrDefault returns the recipe's locale, or the one the provision
// script falls back to.
func localeOrDefault(imageRecipe recipe.Recipe) string {
	if imageRecipe.Locale.Lang == "" {
		return defaultLocale
	}
	return imageRecipe.Locale.Lang
}

// renderFstab mounts the root by its file system's UUID, grown at the first
// boot, and the EFI system partition by its serial, which FAT has instead
// of a UUID, so that a disk missing it still boots.
func renderFstab(ids diskIdentifiers) string {
	return "# Generated by frostroot. The root grows to fill its partition at the first boot.\n" +
		fmt.Sprintf("UUID=%s / ext4 %s 0 1\n", ids.rootFilesystem, diskRootMountOptions) +
		fmt.Sprintf("UUID=%s /boot/efi vfat %s 0 1\n", fatUUID(ids.espSerial), diskESPMountOptions)
}

// fatUUID renders a FAT serial the way the kernel names it: XXXX-XXXX,
// uppercase.
func fatUUID(serial string) string {
	upper := strings.ToUpper(serial)
	return upper[:4] + "-" + upper[4:]
}

// diskRepartConf has systemd-repart grow the root partition to the end of
// the disk at the first boot, whatever disk the image was written to.
const diskRepartConf = "# Generated by frostroot. systemd-repart grows the root partition to the end of the disk at the first boot.\n[Partition]\nType=root\n"

// renderGrubConfig is the one entry GRUB offers: the kernel the image was
// built with, by the links the kernel package keeps, on the root found by
// its UUID, with the console on the screen and the serial line both and the
// screen last, so that the first boot's prompt appears there.
func renderGrubConfig(ids diskIdentifiers) string {
	return "# Generated by frostroot. update-grub never ran in the build and does not need to on this machine.\n" +
		"set default=0\nset timeout=3\n\n" +
		"menuentry 'Ubuntu' {\n" +
		fmt.Sprintf("\tsearch --no-floppy --fs-uuid --set=root %s\n", ids.rootFilesystem) +
		fmt.Sprintf("\tlinux /boot/vmlinuz root=UUID=%s %s\n", ids.rootFilesystem, diskKernelCommandLine) +
		"\tinitrd /boot/initrd.img\n}\n"
}

// renderESPGrubConfig is the three lines on the EFI system partition that
// send the signed GRUB to the root's grub.cfg, beside the binaries in
// EFI/BOOT and EFI/ubuntu, since the signed GRUB is built to look in the
// latter and Ubuntu's patch also tries the directory it was loaded from.
func renderESPGrubConfig(ids diskIdentifiers) string {
	return fmt.Sprintf("search.fs_uuid %s root\nset prefix=($root)'/boot/grub'\nconfigfile $prefix/grub.cfg\n", ids.rootFilesystem)
}

// diskNetplan asks for DHCP on every wired interface, through
// systemd-networkd, the renderer a server image uses.
const diskNetplan = "# Generated by frostroot: DHCP on every wired interface.\nnetwork:\n  version: 2\n  renderer: networkd\n  ethernets:\n    wired:\n      match:\n        name: \"e*\"\n      dhcp4: true\n      dhcp6: true\n"

// diskVconsole is the console keymap, written so that systemd-firstboot
// has nothing to ask at the first boot; localectl changes it.
const diskVconsole = "KEYMAP=us\n"

// setPasswordScript runs at the first boot of a disk image, on the console,
// until the user's password is set. Until then the user's shadow field
// reads "!unprovisioned", so every login fails, and there is no window with
// an empty password. A hypervisor may pass the hash as a credential, which
// is how a headless VM is provisioned. PID 1 is told to hold its status
// messages while the prompt is up, or they print into it. It is bash: its
// kill knows the real-time signals, and bash is essential on Ubuntu. PATH
// is systemd's, which every service gets.
const setPasswordScript = `#!/bin/bash
# Generated by frostroot. Runs at the first boot, on the console, until the
# user's password is set; the unit's condition is the "check" action.
set -eu
action=${1:-}
user=${2:-}
if [ -z "$user" ]; then
	echo "usage: set-password check|set USER" >&2
	exit 2
fi
field() {
	getent shadow "$user" | cut -d: -f2
}
case "$action" in
check)
	# The unit runs only while the password is still to be set: not
	# ConditionFirstBoot, which would make every boot of an unanswered VM a
	# first boot.
	[ "$(field)" = '!unprovisioned' ]
	;;
set)
	credential=${CREDENTIALS_DIRECTORY:-}/passwd.hashed-password.$user
	if [ -n "${CREDENTIALS_DIRECTORY:-}" ] && [ -r "$credential" ]; then
		usermod -p "$(cat "$credential")" "$user"
		exit 0
	fi
	kill -s RTMIN+21 1
	trap 'kill -s RTMIN+20 1' EXIT
	printf '\nfrostroot: set the password of %s to finish this machine.\n' "$user"
	until passwd "$user"; do
		sleep 1
	done
	;;
*)
	echo "usage: set-password check|set USER" >&2
	exit 2
	;;
esac
`

// renderSetPassword returns the set-password program.
func renderSetPassword() string { return setPasswordScript }

// renderSetPasswordUnit is the unit that runs it: after the console is set
// up and plymouth has left it, before any getty, which getty-pre.target
// orders once something wants it; on the console, which is the last
// console= on the kernel command line, the screen. The user's name was
// checked by validate, and has no character a unit file reads.
func renderSetPasswordUnit(userName string) string {
	return "# Generated by frostroot. Enabled by a link under " + diskUnitDir + ", out of reach of presets.\n" +
		"[Unit]\n" +
		fmt.Sprintf("Description=Set the password of %s at the first boot\n", userName) +
		"After=systemd-vconsole-setup.service plymouth-quit-wait.service\n" +
		"Wants=getty-pre.target\nBefore=getty-pre.target display-manager.service\n\n" +
		"[Service]\nType=oneshot\n" +
		fmt.Sprintf("ExecCondition=%s check %s\n", diskSetPasswordPath, userName) +
		fmt.Sprintf("ExecStart=%s set %s\n", diskSetPasswordPath, userName) +
		"ImportCredential=passwd.hashed-password.*\n" +
		"StandardInput=tty\nStandardOutput=tty\nStandardError=tty\nTTYPath=/dev/console\nTTYReset=yes\nTTYVHangup=yes\n\n" +
		"[Install]\nWantedBy=multi-user.target\n"
}

// diskSSHKeygenService makes the SSH host keys at the first boot of a
// 24.04 image that holds openssh-server, whose postinst made keys the
// build removed and which has no unit of its own to make them again.
const diskSSHKeygenService = `# Generated by frostroot. Enabled by a link under /usr/lib/systemd/system, out of reach of presets.
[Unit]
Description=Make the SSH host keys at the first boot
ConditionPathExists=/usr/sbin/sshd
ConditionPathExists=!/etc/ssh/ssh_host_ed25519_key
Before=ssh.service

[Service]
Type=oneshot
ExecStart=/usr/bin/ssh-keygen -A

[Install]
WantedBy=multi-user.target
`

// diskScriptTemplate runs as root inside the image, last, after every
// package's postinst and the provisioning, with every uploaded file in
// place. Recipe values are assigned once, single-quoted, as in the
// provision script.
var diskScriptTemplate = template.Must(template.New("disk").Funcs(template.FuncMap{"shellQuote": shellQuote}).Parse(
	`# Generated by frostroot. Runs as root inside the image, last.
set -eu
PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
export PATH

user={{shellQuote .UserName}}

# The password is set at the first boot by {{.SetPassword}}: until then
# the field reads "!unprovisioned" and every login fails. root stays locked.
usermod -p '!unprovisioned' "$user"
passwd -l root
chmod 0755 {{.SetPassword}}
# The files upload is given to any user to read; netplan wants its own kept.
chmod 0600 {{.Netplan}}

# The resolver is systemd-resolved's, where the WSL image has none.
ln -sfn ../run/systemd/resolve/stub-resolv.conf /etc/resolv.conf

# Enabled statically, under /usr/lib: a first boot re-applies presets.
mkdir -p {{.UnitDir}}/multi-user.target.wants
{{- range .Units}}
ln -sfn ../{{.}} {{$.UnitDir}}/multi-user.target.wants/{{.}}
{{- end}}

# Nothing per machine ships, and machine-id says the first boot is still
# to come; an empty one would not.
rm -f {{range .PerMachine}}{{.}} {{end}}
printf '%s\n' {{.MachineID}} > /etc/machine-id
`))

// diskScriptValues are what the disk script template needs.
type diskScriptValues struct {
	UserName    string
	SetPassword string
	Netplan     string
	UnitDir     string
	Units       []string
	PerMachine  []string
	MachineID   string
}

// renderDiskScript renders the script the last disk hook runs.
func renderDiskScript(imageRecipe recipe.Recipe, release distro.Release) (string, error) {
	units := []string{diskSetPasswordUnit}
	if release.FirstBootSSHKeys {
		units = append(units, diskSSHKeygenUnit)
	}
	var script strings.Builder
	err := diskScriptTemplate.Execute(&script, diskScriptValues{
		UserName:    imageRecipe.User.Name,
		SetPassword: diskSetPasswordPath,
		Netplan:     diskNetplanPath,
		UnitDir:     diskUnitDir,
		Units:       units,
		PerMachine:  diskPerMachineFiles,
		MachineID:   diskMachineIDUninitial,
	})
	if err != nil {
		return "", fmt.Errorf("rendering the disk script: %w", err)
	}
	return script.String(), nil
}

// diskHooks place what a disk image holds beyond a WSL image's provisioning
// and run the disk script, which goes after the Python step, since it points
// the resolver away from what the chroot resolves names with, and before
// the status download. Every file is uploaded, never copied in: upload
// makes the file root's, as the image expects, and names its path itself.
func diskHooks(stage Stage) []string {
	if stage.DiskScriptPath == "" {
		return nil
	}
	var hooks []string
	for _, file := range stage.DiskFiles {
		hooks = append(hooks, `mkdir -p "$1`+filepath.Dir(file.imagePath)+`"`)
		hooks = append(hooks, "upload "+shellQuote(file.hostPath)+" "+file.imagePath)
	}
	return append(hooks, `chroot "$1" /bin/sh -c "$(cat `+shellQuote(stage.DiskScriptPath)+`)" `+diskScriptName)
}
