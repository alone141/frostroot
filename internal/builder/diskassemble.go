package builder

import (
	"context"
	"fmt"
	"path/filepath"
	"strconv"
	"strings"
)

// What the assembly writes into the build's work directory, which a tool
// sees at /work, so every name here is relative to it.
const (
	diskImageName    = "disk.img"
	diskRootName     = "root.ext4"
	diskESPName      = "esp.vfat"
	diskESPFilesName = "esp-files" // where tar puts the boot files out of the tarball
	diskGPTScript    = "gpt.sfdisk"
	diskMke2fsConf   = "mke2fs.conf"
	diskESPGrubName  = "esp-grub.cfg"
)

// Where the tarball keeps the binaries the EFI system partition boots, as
// tar names its members: the shim the lock names, its MokManager beside
// it, and the signed GRUB. Not shimx64.efi.signed, a link whose target
// shim-signed's postinst picks from the build host.
const (
	diskShimDir    = "./usr/lib/shim"
	diskMokManager = "./usr/lib/shim/mmx64.efi"
	diskSignedGrub = "./usr/lib/grub/x86_64-efi-signed/grubx64.efi.signed"
)

// mke2fsConf is what mke2fs makes the root with, whatever the tree's own
// configuration says: Debian's defaults for ext4 as of e2fsprogs 1.47,
// without the orphan_file and metadata_csum_seed features newer defaults
// add, which GRUB's ext2 driver cannot read on every release, and with no
// size-dependent type, so that a small image and a large one are laid out
// the same way.
const mke2fsConf = `# Generated by frostroot: what mke2fs makes a disk image's root with.
[defaults]
	base_features = sparse_super,large_file,filetype,resize_inode,dir_index,ext_attr
	default_mntopts = acl,user_xattr
	enable_periodic_fsck = 0
	blocksize = 4096
	inode_size = 256
	inode_ratio = 16384
	hash_alg = half_md4

[fs_types]
	ext4 = {
		features = has_journal,extent,huge_file,flex_bg,metadata_csum,64bit,dir_nlink,extra_isize
	}
`

// espFile is one file on the EFI system partition and where it comes
// from, relative to /work.
type espFile struct {
	path   string // on the partition, below its root
	source string
}

// espFiles lists what the EFI system partition holds, in the order mcopy
// puts them there, sorted by path: a fresh disk boots from the removable
// path, EFI/BOOT, where shim is BOOTX64.EFI and loads the signed GRUB and
// its MokManager beside it; the stub grub.cfg is there and in EFI/ubuntu,
// where the signed GRUB is built to look.
func espFiles(shim string) []espFile {
	return []espFile{
		{"EFI/BOOT/BOOTX64.EFI", diskESPFilesName + "/" + strings.TrimPrefix(diskShimDir, "./") + "/" + shim},
		{"EFI/BOOT/grub.cfg", diskESPGrubName},
		{"EFI/BOOT/grubx64.efi", diskESPFilesName + "/" + strings.TrimPrefix(diskSignedGrub, "./")},
		{"EFI/BOOT/mmx64.efi", diskESPFilesName + "/" + strings.TrimPrefix(diskMokManager, "./")},
		{"EFI/ubuntu/grub.cfg", diskESPGrubName},
	}
}

// renderSfdiskScript renders the partition table for sfdisk: GPT with the
// layout's own id, the EFI system partition from the first MiB and the
// root after it, each with its UUID, type and the name systemd-repart
// gives such a partition, and the root marked to be grown, as repart marks
// it. Without the ids sfdisk would draw random ones.
func renderSfdiskScript(layout diskLayout) string {
	ids := layout.identifiers()
	espSectors := layout.espBytes / diskSectorBytes
	rootStart := (diskFirstPartition + layout.espBytes) / diskSectorBytes
	return "label: gpt\n" +
		"label-id: " + ids.disk + "\n" +
		"unit: sectors\n" +
		"first-lba: " + strconv.FormatInt(diskFirstPartition/diskSectorBytes, 10) + "\n" +
		"sector-size: " + strconv.Itoa(diskSectorBytes) + "\n\n" +
		fmt.Sprintf("start=%d, size=%d, type=%s, uuid=%s, name=\"%s\"\n", diskFirstPartition/diskSectorBytes, espSectors, espPartitionType, ids.espPartition, espPartitionName) +
		fmt.Sprintf("start=%d, size=%d, type=%s, uuid=%s, name=\"%s\", attrs=\"GUID:59\"\n", rootStart, layout.rootBytes/diskSectorBytes, rootPartitionType, ids.rootPartition, rootPartitionName)
}

// diskAssembly makes the disk in the build's work directory, with the
// tools tree, from the tarball there.
type diskAssembly struct {
	runner   ToolRunner
	treeDir  string
	workDir  string
	tarball  string // the tarball's name in the work directory
	layout   diskLayout
	epoch    int64
	progress Progress
}

// assemble makes the root file system out of the tarball, the EFI system
// partition with the boot files out of the same tarball, the partition
// table, and places both partitions in the raw image, as the assembly
// phase, and returns the image's path. The raw image is sparse: dd skips
// what is zero, and the file was made with holes.
func (a *diskAssembly) assemble(ctx context.Context) (string, error) {
	a.progress.Report(ProgressEvent{Phase: PhaseAssembleDisk, Kind: EventPhaseStarted})
	ids := a.layout.identifiers()
	for name, content := range map[string]string{
		diskMke2fsConf:  mke2fsConf,
		diskGPTScript:   renderSfdiskScript(a.layout),
		diskESPGrubName: renderESPGrubConfig(ids),
	} {
		if err := writeStageFile(filepath.Join(a.workDir, name), []byte(content)); err != nil {
			return "", fmt.Errorf("assembling the disk: %w", err)
		}
	}
	if err := makeDirectoriesWithMode(filepath.Join(a.workDir, diskESPFilesName), 0o755); err != nil {
		return "", fmt.Errorf("assembling the disk: %w", err)
	}
	steps := []struct {
		tool      string
		args      []string
		variables [][2]string
	}{
		// The root: a fresh file of the partition's size, filled from the
		// tarball, with the file system's UUID and the seed its directories
		// hash with, nothing discarded and the inode tables left for the
		// kernel to initialize, under frostroot's own configuration.
		{"truncate", []string{"-s", strconv.FormatInt(a.layout.rootBytes, 10), diskRootName}, nil},
		{"mke2fs", []string{"-q", "-F", "-t", "ext4", "-d", a.tarball, "-U", ids.rootFilesystem,
			"-E", "nodiscard,lazy_itable_init=1,hash_seed=" + ids.rootHashSeed, diskRootName},
			[][2]string{{"MKE2FS_CONFIG", toolWorkMount + "/" + diskMke2fsConf}}},
		// The EFI system partition: FAT32 with the serial, --invariant for
		// the rest, then the boot files out of the tarball, one mcopy each,
		// in sorted order; mtools dates them by SOURCE_DATE_EPOCH.
		{"truncate", []string{"-s", strconv.FormatInt(a.layout.espBytes, 10), diskESPName}, nil},
		{"mkfs.fat", []string{"-F", "32", "--invariant", "-i", ids.espSerial, diskESPName}, nil},
		{"tar", []string{"-xf", a.tarball, "-C", diskESPFilesName, diskShimDir + "/" + a.layout.shim, diskMokManager, diskSignedGrub}, nil},
		{"mmd", []string{"-i", diskESPName, "::/EFI", "::/EFI/BOOT", "::/EFI/ubuntu"}, nil},
	}
	for _, file := range espFiles(a.layout.shim) {
		steps = append(steps, struct {
			tool      string
			args      []string
			variables [][2]string
		}{"mcopy", []string{"-i", diskESPName, file.source, "::/" + file.path}, nil})
	}
	steps = append(steps, []struct {
		tool      string
		args      []string
		variables [][2]string
	}{
		// The disk: a sparse file of its size, the table written from the
		// script on sfdisk's standard input, which the tree's sh opens,
		// then each partition placed at its offset without truncating.
		{"truncate", []string{"-s", strconv.FormatInt(a.layout.diskBytes, 10), diskImageName}, nil},
		{"sh", []string{"-c", `exec sfdisk "$@" < ` + diskGPTScript, "sh", "--no-reread", "--no-tell-kernel", diskImageName}, nil},
		{"dd", []string{"if=" + diskESPName, "of=" + diskImageName, "bs=1M", "seek=" + strconv.FormatInt(diskFirstPartition/diskMiB, 10), "conv=notrunc,sparse", "status=none"}, nil},
		{"dd", []string{"if=" + diskRootName, "of=" + diskImageName, "bs=1M", "seek=" + strconv.FormatInt((diskFirstPartition+a.layout.espBytes)/diskMiB, 10), "conv=notrunc,sparse", "status=none"}, nil},
	}...)
	for _, step := range steps {
		a.progress.Report(ProgressEvent{Phase: PhaseAssembleDisk, Kind: EventLogLine, Line: "$ " + step.tool + " " + strings.Join(step.args, " ")})
		output := &lineSplitter{emit: func(line string) {
			a.progress.Report(ProgressEvent{Phase: PhaseAssembleDisk, Kind: EventLogLine, Line: line})
		}}
		err := a.runner.Run(ctx, ToolRun{
			TreeDir: a.treeDir, WorkDir: a.workDir, Tool: step.tool, Args: step.args,
			SourceDateEpoch: a.epoch, Variables: step.variables, Stdout: output, Stderr: output,
		})
		output.flush()
		if err != nil {
			return "", fmt.Errorf("assembling the disk: %w", err)
		}
	}
	a.progress.Report(ProgressEvent{Phase: PhaseAssembleDisk, Kind: EventPhaseFinished})
	return filepath.Join(a.workDir, diskImageName), nil
}
